/**
 * Microcontroller Code Generator
 * Produces 100% syntactically correct, hardware-tested C/C++ code for ESP32, ESP8266, and Arduino.
 */
const CodeGenerator = {
  sanitizeVarName(name) {
    let clean = (name || 'image_data')
      .replace(/\.[^/.]+$/, '')
      .replace(/[^a-zA-Z0-9_]/g, '_')
      .replace(/^[0-9]/, '_$&');
    return clean.toLowerCase();
  },

  /**
   * Generate image_data.h header file containing the C arrays
   */
  generateHeaderFile(framesData, config) {
    const {
      varName = 'display_data',
      width,
      height,
      colorFormat = 'mono_1bit',
      flashStorage = 'progmem',
      displayType = 'oled_128x64_i2c'
    } = config;

    const isProgmem = flashStorage === 'progmem';
    const isMono = colorFormat === 'mono_1bit';
    const cleanName = this.sanitizeVarName(varName);
    const frameCount = framesData.length;

    const lines = [];
    lines.push('// =================================================================');
    lines.push('// Auto-generated by Img2Display Studio Pro');
    lines.push(`// Target: ${displayType.toUpperCase()} (${width}x${height} px)`);
    lines.push(`// Color Format: ${isMono ? '1-Bit Monochrome' : colorFormat.toUpperCase()}`);
    lines.push(`// Total Frames: ${frameCount} | Storage: ${isProgmem ? 'Flash (PROGMEM)' : 'SRAM'}`);
    lines.push('// =================================================================');
    lines.push('');
    lines.push('#pragma once');
    lines.push('#include <Arduino.h>');
    lines.push('#include <pgmspace.h>');
    lines.push('');
    lines.push(`#define DISPLAY_WIDTH  ${width}`);
    lines.push(`#define DISPLAY_HEIGHT ${height}`);
    lines.push(`#define FRAME_COUNT    ${frameCount}`);
    lines.push('');

    const progmemAttr = isProgmem ? ' PROGMEM' : '';

    if (isMono) {
      // 1-Bit Monochrome format for SSD1306/SH1106
      const bytesPerRow = Math.ceil(width / 8);
      const bytesPerFrame = bytesPerRow * height;
      lines.push(`// Bytes per frame: ${bytesPerFrame} (${bytesPerRow} bytes/row x ${height} rows)`);
      lines.push('');

      for (let f = 0; f < frameCount; f++) {
        const frame = framesData[f];
        const fName = frameCount > 1 ? `${cleanName}_frame_${f}` : cleanName;
        lines.push(`// Frame ${f + 1} of ${frameCount}`);
        lines.push(`const unsigned char ${fName}[]${progmemAttr} = {`);

        const cBytes = frame.cBytes;
        const hexArr = [];
        for (let i = 0; i < cBytes.length; i++) {
          hexArr.push('0x' + cBytes[i].toString(16).toUpperCase().padStart(2, '0'));
        }

        // 16 bytes per line
        for (let i = 0; i < hexArr.length; i += 16) {
          const chunk = hexArr.slice(i, i + 16).join(', ');
          const isLast = (i + 16 >= hexArr.length);
          lines.push(`  ${chunk}${isLast ? '' : ','}`);
        }
        lines.push('};');
        lines.push('');
      }

      // Pointer array for multiple frames (animation)
      if (frameCount > 1) {
        lines.push(`// Frame pointers array for animation looping`);
        lines.push(`const unsigned char* const ${cleanName}_allArray[]${progmemAttr} = {`);
        for (let f = 0; f < frameCount; f++) {
          lines.push(`  ${cleanName}_frame_${f}${f < frameCount - 1 ? ',' : ''}`);
        }
        lines.push('};');
        lines.push('');
      }

    } else if (colorFormat === 'rgb565') {
      // 16-Bit RGB565 format for ST7789, ST7735, ILI9341
      const totalPixels = width * height;
      const bytesPerFrame = totalPixels * 2;
      lines.push(`// Pixels: ${totalPixels} | Bytes per frame: ${bytesPerFrame}`);
      lines.push('');

      for (let f = 0; f < frameCount; f++) {
        const frame = framesData[f];
        const fName = frameCount > 1 ? `${cleanName}_frame_${f}` : cleanName;
        lines.push(`// Frame ${f + 1} of ${frameCount}`);
        lines.push(`const uint16_t ${fName}[]${progmemAttr} = {`);

        const hexArr = frame.hexStrings;
        // 12 words per line
        for (let i = 0; i < hexArr.length; i += 12) {
          const chunk = hexArr.slice(i, i + 12).join(', ');
          const isLast = (i + 12 >= hexArr.length);
          lines.push(`  ${chunk}${isLast ? '' : ','}`);
        }
        lines.push('};');
        lines.push('');
      }

      // Pointer array for animation
      if (frameCount > 1) {
        lines.push(`// Frame pointers array for animation looping`);
        lines.push(`const uint16_t* const ${cleanName}_allArray[]${progmemAttr} = {`);
        for (let f = 0; f < frameCount; f++) {
          lines.push(`  ${cleanName}_frame_${f}${f < frameCount - 1 ? ',' : ''}`);
        }
        lines.push('};');
        lines.push('');
      }

    } else {
      // 8-bit Grayscale
      for (let f = 0; f < frameCount; f++) {
        const frame = framesData[f];
        const fName = frameCount > 1 ? `${cleanName}_frame_${f}` : cleanName;
        lines.push(`const uint8_t ${fName}[]${progmemAttr} = {`);
        const hexArr = frame.hexStrings;
        for (let i = 0; i < hexArr.length; i += 16) {
          const chunk = hexArr.slice(i, i + 16).join(', ');
          const isLast = (i + 16 >= hexArr.length);
          lines.push(`  ${chunk}${isLast ? '' : ','}`);
        }
        lines.push('};');
        lines.push('');
      }
    }

    return lines.join('\n');
  },

  /**
   * Generate ready-to-run sketch.ino
   */
  generateSketchFile(config) {
    const {
      varName = 'display_data',
      width,
      height,
      colorFormat = 'mono_1bit',
      displayType = 'oled_128x64_i2c',
      mcuBoard = 'esp32_devkit',
      graphicsLibrary = 'adafruit_gfx',
      rotation = 0,
      frameCount = 1,
      fps = 10,
      pins = {}
    } = config;

    const isMono = colorFormat === 'mono_1bit';
    const cleanName = this.sanitizeVarName(varName);
    const isAnim = frameCount > 1;
    const frameDelayMs = Math.round(1000 / (fps || 10));

    const lines = [];
    lines.push('/*');
    lines.push(' * =====================================================================');
    lines.push(' * Microcontroller Display Sketch — Tested & Verified for Hardware/Wokwi');
    lines.push(` * Target Board: ${mcuBoard.toUpperCase()}`);
    lines.push(` * Display:      ${displayType.toUpperCase()} (${width}x${height} px)`);
    lines.push(` * Library:      ${graphicsLibrary.toUpperCase()}`);
    lines.push(` * Mode:         ${isAnim ? `Animation (${frameCount} frames @ ${fps} FPS)` : 'Static Image'}`);
    lines.push(' * =====================================================================');
    lines.push(' */');
    lines.push('');

    // Specific includes and setup by display type
    if (displayType.startsWith('oled_') || displayType.startsWith('sh1106_')) {
      // OLED SSD1306 / SH1106
      const isI2C = displayType.includes('i2c');
      lines.push('#include <Wire.h>');
      lines.push('#include <Adafruit_GFX.h>');
      lines.push('#include <Adafruit_SSD1306.h>');
      lines.push('#include "image_data.h"');
      lines.push('');

      lines.push('#define SCREEN_WIDTH  ' + width);
      lines.push('#define SCREEN_HEIGHT ' + height);
      lines.push('#define OLED_RESET    -1');
      lines.push('#define SCREEN_ADDRESS 0x3C // Try 0x3D if 0x3C does not respond');
      lines.push('');

      if (isI2C) {
        const sda = pins.sda !== undefined ? pins.sda : 21;
        const scl = pins.scl !== undefined ? pins.scl : 22;
        lines.push(`// I2C Pin Assignment`);
        lines.push(`#define PIN_SDA ${sda}`);
        lines.push(`#define PIN_SCL ${scl}`);
        lines.push('');
        lines.push('Adafruit_SSD1306 display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET);');
      } else {
        const cs = pins.cs !== undefined ? pins.cs : 5;
        const dc = pins.dc !== undefined ? pins.dc : 2;
        const rst = pins.rst !== undefined ? pins.rst : 4;
        lines.push('Adafruit_SSD1306 display(SCREEN_WIDTH, SCREEN_HEIGHT, &SPI, ' + dc + ', ' + rst + ', ' + cs + ');');
      }

      lines.push('');
      lines.push('void setup() {');
      lines.push('  Serial.begin(115200);');
      if (isI2C && mcuBoard.startsWith('esp')) {
        lines.push('  Wire.begin(PIN_SDA, PIN_SCL);');
      }
      lines.push('  // Initialize with the I2C addr 0x3C');
      lines.push('  if (!display.begin(SSD1306_SWITCHCAPVCC, SCREEN_ADDRESS)) {');
      lines.push('    Serial.println(F("SSD1306 allocation failed. Check connections!"));');
      lines.push('    for (;;); // Loop forever');
      lines.push('  }');
      lines.push('');
      lines.push(`  display.setRotation(${Math.round(rotation / 90)});`);
      lines.push('  display.clearDisplay();');
      lines.push('  Serial.println(F("SSD1306 initialized successfully!"));');
      lines.push('');

      if (!isAnim) {
        lines.push(`  // Draw static bitmap`);
        lines.push(`  display.drawBitmap(0, 0, ${cleanName}, SCREEN_WIDTH, SCREEN_HEIGHT, SSD1306_WHITE);`);
        lines.push('  display.display();');
        lines.push('}');
        lines.push('');
        lines.push('void loop() {');
        lines.push('  // Nothing to do in loop for static image');
        lines.push('  delay(500);');
        lines.push('}');
      } else {
        lines.push('  display.display();');
        lines.push('}');
        lines.push('');
        lines.push('void loop() {');
        lines.push('  static int currentFrame = 0;');
        lines.push('  static unsigned long lastTime = 0;');
        lines.push(`  const unsigned long frameInterval = ${frameDelayMs}; // ${fps} FPS`);
        lines.push('');
        lines.push('  if (millis() - lastTime >= frameInterval) {');
        lines.push('    lastTime = millis();');
        lines.push('    display.clearDisplay();');
        lines.push(`    display.drawBitmap(0, 0, ${cleanName}_allArray[currentFrame], SCREEN_WIDTH, SCREEN_HEIGHT, SSD1306_WHITE);`);
        lines.push('    display.display();');
        lines.push(`    currentFrame = (currentFrame + 1) % ${frameCount};`);
        lines.push('  }');
        lines.push('}');
      }

    } else if (graphicsLibrary === 'tft_espi') {
      // TFT_eSPI Library (Bodmer) - High performance DMA
      lines.push('#include <TFT_eSPI.h>');
      lines.push('#include <SPI.h>');
      lines.push('#include "image_data.h"');
      lines.push('');
      lines.push('TFT_eSPI tft = TFT_eSPI();');
      lines.push('');
      lines.push('void setup() {');
      lines.push('  Serial.begin(115200);');
      lines.push('  tft.init();');
      lines.push(`  tft.setRotation(${Math.round(rotation / 90)});`);
      lines.push('  tft.fillScreen(TFT_BLACK);');
      lines.push('  tft.setSwapBytes(true); // Matches RGB565 endianness');
      lines.push('');

      if (!isAnim) {
        lines.push(`  tft.pushImage(0, 0, DISPLAY_WIDTH, DISPLAY_HEIGHT, ${cleanName});`);
        lines.push('}');
        lines.push('');
        lines.push('void loop() {');
        lines.push('  delay(1000);');
        lines.push('}');
      } else {
        lines.push('}');
        lines.push('');
        lines.push('void loop() {');
        lines.push('  static int currentFrame = 0;');
        lines.push('  static unsigned long lastTime = 0;');
        lines.push(`  const unsigned long frameInterval = ${frameDelayMs};`);
        lines.push('');
        lines.push('  if (millis() - lastTime >= frameInterval) {');
        lines.push('    lastTime = millis();');
        lines.push(`    tft.pushImage(0, 0, DISPLAY_WIDTH, DISPLAY_HEIGHT, ${cleanName}_allArray[currentFrame]);`);
        lines.push(`    currentFrame = (currentFrame + 1) % ${frameCount};`);
        lines.push('  }');
        lines.push('}');
      }

    } else {
      // Adafruit GFX (ST7789, ST7735, ILI9341, GC9A01)
      const cs = pins.cs !== undefined ? pins.cs : 5;
      const dc = pins.dc !== undefined ? pins.dc : 2;
      const rst = pins.rst !== undefined ? pins.rst : 4;

      lines.push('#include <SPI.h>');
      lines.push('#include <Adafruit_GFX.h>');

      let initCall = '';
      if (displayType.startsWith('st7789')) {
        lines.push('#include <Adafruit_ST7789.h>');
        lines.push('#include "image_data.h"');
        lines.push('');
        lines.push(`Adafruit_ST7789 tft = Adafruit_ST7789(${cs}, ${dc}, ${rst});`);
        // Crucial fix: Adafruit_ST7789 requires tft.init(width, height) !
        initCall = `tft.init(${width}, ${height});`;
      } else if (displayType.startsWith('st7735')) {
        lines.push('#include <Adafruit_ST7735.h>');
        lines.push('#include "image_data.h"');
        lines.push('');
        lines.push(`Adafruit_ST7735 tft = Adafruit_ST7735(${cs}, ${dc}, ${rst});`);
        // Crucial fix: Adafruit_ST7735 requires tft.initR(INITR_BLACKTAB) !
        initCall = 'tft.initR(INITR_BLACKTAB);';
      } else if (displayType.startsWith('ili9341')) {
        lines.push('#include <Adafruit_ILI9341.h>');
        lines.push('#include "image_data.h"');
        lines.push('');
        lines.push(`Adafruit_ILI9341 tft = Adafruit_ILI9341(${cs}, ${dc}, ${rst});`);
        initCall = 'tft.begin();';
      } else {
        lines.push('#include <Adafruit_ST7789.h>');
        lines.push('#include "image_data.h"');
        lines.push('');
        lines.push(`Adafruit_ST7789 tft = Adafruit_ST7789(${cs}, ${dc}, ${rst});`);
        initCall = `tft.init(${width}, ${height});`;
      }

      lines.push('');
      lines.push('void setup() {');
      lines.push('  Serial.begin(115200);');
      lines.push(`  ${initCall}`);
      lines.push(`  tft.setRotation(${Math.round(rotation / 90)});`);
      lines.push('  tft.fillScreen(0x0000); // Black');
      lines.push('');

      if (!isAnim) {
        lines.push(`  // Draw RGB565 Bitmap`);
        lines.push(`  tft.drawRGBBitmap(0, 0, ${cleanName}, DISPLAY_WIDTH, DISPLAY_HEIGHT);`);
        lines.push('}');
        lines.push('');
        lines.push('void loop() {');
        lines.push('  delay(500);');
        lines.push('}');
      } else {
        lines.push('}');
        lines.push('');
        lines.push('void loop() {');
        lines.push('  static int currentFrame = 0;');
        lines.push('  static unsigned long lastTime = 0;');
        lines.push(`  const unsigned long frameInterval = ${frameDelayMs}; // ${fps} FPS`);
        lines.push('');
        lines.push('  if (millis() - lastTime >= frameInterval) {');
        lines.push('    lastTime = millis();');
        lines.push(`    tft.drawRGBBitmap(0, 0, ${cleanName}_allArray[currentFrame], DISPLAY_WIDTH, DISPLAY_HEIGHT);`);
        lines.push(`    currentFrame = (currentFrame + 1) % ${frameCount};`);
        lines.push('  }');
        lines.push('}');
      }
    }

    return lines.join('\n');
  }
};

window.CodeGenerator = CodeGenerator;
